"""Builds dist/Code.gs: the Apps Script server code with the sidebar inlined, ready to paste."""
from pathlib import Path
import base64
import hashlib
import json

root = Path(__file__).resolve().parent
key = json.loads((root / 'extension' / 'manifest.json').read_text())['key']
digest = hashlib.sha256(base64.b64decode(key)).hexdigest()[:32]
extension_id = ''.join(chr(ord('a') + int(c, 16)) for c in digest)

server = (root / 'apps-script' / 'Server.gs').read_text()
sidebar = (root / 'apps-script' / 'Sidebar.html').read_text().replace('__EXTENSION_ID__', extension_id)
(root / 'dist').mkdir(exist_ok=True)
(root / 'dist' / 'Code.gs').write_text(
    '// Generated by build.py from apps-script/Server.gs and apps-script/Sidebar.html. Do not edit.\n' +
    server + '\nfunction sidebarHtml_() { return ' + json.dumps(sidebar, ensure_ascii=True) + '; }\n')
print('Built dist/Code.gs for extension', extension_id)
